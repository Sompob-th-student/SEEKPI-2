// Build migrations/0001_init.sql for Cloudflare D1 from the Node prototype:
// 1. create a fresh SQLite file with server/db.js (schema + Syntec demo data) and compute every score (server/scoring.js)
// 2. dump schema + rows as plain SQL that `wrangler d1 migrations apply` can run
// 3. replace the bcrypt demo password hashes with PBKDF2 hashes (the Worker verifies PBKDF2 via WebCrypto)
// Usage: node scripts/build-seed.mjs   (from seekpi-2/cloudflare)
import { mkdtempSync, writeFileSync, mkdirSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { pbkdf2Sync, randomBytes } from 'node:crypto';

const here = dirname(fileURLToPath(import.meta.url));
process.env.SEEKPI_DB = join(mkdtempSync(join(tmpdir(), 'seekpi2-seed-')), 'seed.db');
const { db } = await import('../../server/db.js');
const { recalculateAll } = await import('../../server/scoring.js');
recalculateAll();

// Demo accounts (documented in README-DEPLOY.md). Change them after the first login.
const DEMO_PASSWORDS = { admin: 'admin123', hr: 'hr123', E0001: 'demo123', E0002: 'demo123' };
const pbkdf2 = (pw) => {
  const salt = randomBytes(16), it = 100000;
  return `pbkdf2$${it}$${salt.toString('base64')}$${pbkdf2Sync(pw, salt, it, 32, 'sha256').toString('base64')}`;
};

const q = (sql, ...p) => db.prepare(sql).all(...p);
const lit = (v) => {
  if (v === null || v === undefined) return 'NULL';
  if (typeof v === 'number' || typeof v === 'bigint') return String(v);
  if (v instanceof Uint8Array) return `X'${Buffer.from(v).toString('hex')}'`;
  return `'${String(v).replace(/'/g, "''")}'`;
};

const out = [
  '-- SEEKPI-2 · Cloudflare D1 initial migration (schema + Syntec demo data, scores precomputed)',
  `-- Generated by scripts/build-seed.mjs on ${new Date().toISOString()}`,
  'PRAGMA defer_foreign_keys = true;',
  '',
];
const objects = q("SELECT type, name, tbl_name, sql FROM sqlite_master WHERE sql IS NOT NULL AND name NOT LIKE 'sqlite_%' ORDER BY CASE type WHEN 'table' THEN 0 WHEN 'index' THEN 1 ELSE 2 END, rowid");
const tables = objects.filter((o) => o.type === 'table');
for (const t of tables) out.push(`${t.sql};`);
out.push('');
let rows = 0;
for (const t of tables) {
  const data = q(`SELECT * FROM "${t.name}"`);
  if (!data.length) continue;
  const cols = Object.keys(data[0]);
  for (const r of data) {
    if (t.name === 'user' && DEMO_PASSWORDS[r.user_name]) r.password_hash = pbkdf2(DEMO_PASSWORDS[r.user_name]);
    out.push(`INSERT INTO "${t.name}" (${cols.map((c) => `"${c}"`).join(',')}) VALUES (${cols.map((c) => lit(r[c])).join(',')});`);
    rows++;
  }
}
for (const o of objects.filter((x) => x.type !== 'table')) out.push(`${o.sql};`);
// usage log rows from the seed run are not useful in production
out.push('DELETE FROM usage_log;');

const file = join(here, '..', 'migrations', '0001_init.sql');
mkdirSync(dirname(file), { recursive: true });
writeFileSync(file, out.join('\n') + '\n');
console.log(`wrote ${file}: ${tables.length} tables, ${rows} rows`);
